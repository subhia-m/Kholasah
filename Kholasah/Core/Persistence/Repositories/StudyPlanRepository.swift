// عقد يحدد قراءة الخطط وحفظها وحذفها دون ربط المستدعي بطريقة تخزين معينة.
// للقراءة: let يثبت القيمة، وvar يسمح بتغييرها، وprivate يحصر الوصول في نطاق التعريف.

import Foundation

// يحصر الوصول إلى هذا النوع في الممثل الرئيسي لتنسيق التغييرات المرتبطة بالواجهة.
@MainActor
// protocol عقد يحدد المتطلبات؛ النوع المطابق له يقدم التنفيذ الفعلي.
protocol StudyPlanRepository: AnyObject {
    // الخطط المتاحة من مصدر البيانات.
    var plans: [StudyPlan] { get }
    // يتحقق من العنوان ثم يرسل الحفظ إلى الأب ويغلق نافذة التحرير.
    func save(_ plan: StudyPlan)
    // يحذف العنصر المطابق للمعرّف.
    func remove(id: StudyPlan.ID)
}
